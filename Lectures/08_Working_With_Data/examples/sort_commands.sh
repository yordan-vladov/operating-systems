# Сортира числата от numbers.txt числово (1, 38, 45, 123, 2000).
# Без -n сортирането е текстово и "123" би било преди "38".
sort -n numbers.txt

# Сортира числово, но в низходящ ред (2000, 123, 45, 38, 1)
sort -rn numbers.txt

# Сортира изхода на "ls -l" по 8-мата колона (час/година на последна промяна).
# Колоните са разделени с интервали: права, връзки, собственик, група,
# размер, месец, ден, час/година, име
ls -l | sort -k 8

# Сортира файловете по размер (5-тата колона), числово
ls -l | sort -nk 5

# Колоните в /etc/passwd са разделени с ":", затова задаваме разделител с -t.
# Сортираме числово по 4-тата колона (GID - номер на основната група)
cat /etc/passwd | sort -t ":" -nk 4
