# uniq премахва само ПОСЛЕДОВАТЕЛНИТЕ повтарящи се редове.
# Резултат: Peter, James, John, Mary, John, Peter
# (трите "Mary" се сливат в един ред, но "John" и "Peter" остават по два пъти)
uniq names.txt

# За да премахнем всички повторения, първо сортираме -
# така еднаквите редове застават един до друг и uniq ги слива.
# Резултат: всяка команда от историята се показва само веднъж
cat history.txt | sort | uniq
