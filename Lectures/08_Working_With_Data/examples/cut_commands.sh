# Разделя всеки ред на /etc/passwd по ":" и оставя само 1-вата колона
# (потребителските имена)
cut -d: -f1 /etc/passwd

# Оставя 1-вата и 3-тата колона (потребителско име и UID)
cut -d: -f1,3 /etc/passwd

# Оставя колоните от 1-вата до 3-тата включително
# (потребителско име, парола (x) и UID)
cut -d: -f1-3 /etc/passwd

# Взима 7-мата колона (shell-а на всеки потребител), сортира,
# и с "uniq -c" брои колко потребители използват всеки shell
cat /etc/passwd | cut -d: -f7 | sort | uniq -c
